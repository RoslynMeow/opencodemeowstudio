const dictionaries: Record<Locale, Record<string, string>> = { en, "zh-CN": zh }

let activeLocale: Locale = "en"

export function resolveLocale(language: string | undefined, systemLocale: string | undefined): Locale {
  if (language === "en" || language === "zh-CN") return language
  const value = (systemLocale ?? "en").toLowerCase()
  return value.startsWith("zh") ? "zh-CN" : "en"
}

export function setLocale(locale: Locale): void {
  activeLocale = locale
}

export function getLocale(): Locale {
  return activeLocale
}

export function translate(locale: Locale, key: string, vars?: Vars): string {
  const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = vars[name]
    return value === undefined ? `{${name}}` : String(value)
  })
}

export function tr(key: string, vars?: Vars): string {
  return translate(activeLocale, key, vars)
}
